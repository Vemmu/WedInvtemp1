import type { Metadata, Viewport } from "next";
import { Rozha_One, Tiro_Devanagari_Hindi, Mukta } from "next/font/google";
import { wedding } from "@/config/wedding";
import { formatLongDate } from "@/lib/date";
import "./globals.css";

/* Self-hosted Google fonts, each covering both Latin and Devanagari */
const display = Rozha_One({ subsets: ["latin", "devanagari"], weight: "400", variable: "--font-display", display: "swap" });
const serif = Tiro_Devanagari_Hindi({ subsets: ["latin", "devanagari"], weight: "400", style: ["normal", "italic"], variable: "--font-serif", display: "swap" });
const sans = Mukta({ subsets: ["latin", "devanagari"], weight: ["300", "400", "500", "600"], variable: "--font-sans", display: "swap" });

const { bride, groom, seo, city, weddingDate } = wedding;

/**
 * Open Graph / Twitter metadata: the WhatsApp link preview.
 * The image is generated by ./opengraph-image.tsx. Set NEXT_SITE_URL in production.
 */
export const metadata: Metadata = {
  metadataBase: new URL(wedding.siteUrl),
  title: seo.title,
  description: seo.description,
  applicationName: `${bride.firstName} & ${groom.firstName}`,
  openGraph: {
    type: "website",
    title: `${bride.firstName} & ${groom.firstName}: Shubh Vivah`,
    description: `${formatLongDate(weddingDate)} · ${city}. ${seo.description}`,
    siteName: `${bride.firstName} & ${groom.firstName}`,
    locale: "en_IN",
    url: "/",
  },
  twitter: { card: "summary_large_image", title: `${bride.firstName} & ${groom.firstName}: Shubh Vivah`, description: seo.description },
  robots: { index: false, follow: false },
};

export const viewport: Viewport = {
  themeColor: "#5E0814",
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${display.variable} ${serif.variable} ${sans.variable}`}>
      <body>{children}</body>
    </html>
  );
}
